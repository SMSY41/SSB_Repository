# %matplotlib inline

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from sklearn.preprocessing import MinMaxScaler
from sklearn.metrics import mean_squared_error, mean_absolute_error, r2_score
import tensorflow as tf
from tensorflow.keras.models import Model
from tensorflow.keras.layers import (
    Input, LSTM, GRU, Dense, Dropout, Conv1D, MaxPooling1D,
    MultiHeadAttention, LayerNormalization, GlobalAveragePooling1D, Add
)
from tensorflow.keras.callbacks import EarlyStopping, ReduceLROnPlateau
from tensorflow.keras.optimizers import Adam
import time

np.random.seed(42)
tf.random.set_seed(42)

# ============================================================
# 1. LOAD DATA
# ============================================================
df = pd.read_csv('SSB_SOH_MASTER.csv')
print(f"Rows: {len(df)}")
print(f"SOH range: {df['SOH'].min():.3f} to {df['SOH'].max():.3f}")
print(f"Runs: {df['Run_ID'].nunique()}")

# ============================================================
# 2. FEATURE ENGINEERING PER RUN
# ============================================================
def engineer_features(group):
    group = group.copy().sort_values('Time_s').reset_index(drop=True)
    dt = group['Time_s'].diff().fillna(0)
    group['Cumulative_Charge'] = (group['Current_A'] * dt).cumsum()
    group['Voltage_Diff'] = group['Voltage_V'].diff().fillna(0)
    return group

df = df.groupby('Run_ID', group_keys=False).apply(engineer_features).reset_index(drop=True)

# Features (Cycle is key for SOH)
feature_cols = ['Current_A', 'Voltage_V', 'Cumulative_Charge', 'Voltage_Diff', 'Cycle']
target_col = 'SOH'

scaler_X = MinMaxScaler()
scaler_y = MinMaxScaler()
X_scaled = scaler_X.fit_transform(df[feature_cols].values)
y_scaled = scaler_y.fit_transform(df[[target_col]].values)

# ============================================================
# 3. SEQUENCES PER RUN
# ============================================================
WINDOW_SIZE = 30
X_seq, y_seq = [], []

for run_id in sorted(df['Run_ID'].unique()):
    mask = (df['Run_ID'] == run_id).values
    X_run = X_scaled[mask]
    y_run = y_scaled[mask]
    if len(X_run) <= WINDOW_SIZE:
        continue
    for i in range(len(X_run) - WINDOW_SIZE):
        X_seq.append(X_run[i:i + WINDOW_SIZE])
        y_seq.append(y_run[i + WINDOW_SIZE])

X_seq = np.array(X_seq)
y_seq = np.array(y_seq)
print(f"Sequences: {X_seq.shape}")

idx = np.random.permutation(len(X_seq))
X_seq, y_seq = X_seq[idx], y_seq[idx]

n = len(X_seq)
n_train = int(0.70 * n)
n_val = int(0.15 * n)

X_train, y_train = X_seq[:n_train], y_seq[:n_train]
X_val, y_val = X_seq[n_train:n_train + n_val], y_seq[n_train:n_train + n_val]
X_test, y_test = X_seq[n_train + n_val:], y_seq[n_train + n_val:]

print(f"Train: {X_train.shape}, Val: {X_val.shape}, Test: {X_test.shape}")

# ============================================================
# 4. MODELS
# ============================================================
input_shape = (WINDOW_SIZE, len(feature_cols))

def build_lstm():
    inputs = Input(shape=input_shape)
    x = LSTM(32, return_sequences=True)(inputs); x = Dropout(0.3)(x)
    x = LSTM(16)(x); x = Dropout(0.3)(x)
    x = Dense(8, activation='relu')(x)
    outputs = Dense(1)(x)
    m = Model(inputs, outputs, name='LSTM')
    m.compile(optimizer=Adam(1e-3), loss='mse', metrics=['mae'])
    return m

def build_gru():
    inputs = Input(shape=input_shape)
    x = GRU(32, return_sequences=True)(inputs); x = Dropout(0.3)(x)
    x = GRU(16)(x); x = Dropout(0.3)(x)
    x = Dense(8, activation='relu')(x)
    outputs = Dense(1)(x)
    m = Model(inputs, outputs, name='GRU')
    m.compile(optimizer=Adam(1e-4), loss='mse', metrics=['mae'])
    return m

def transformer_block(inputs, head_size=16, num_heads=2, ff_dim=32, dropout=0.2):
    attn = MultiHeadAttention(num_heads=num_heads, key_dim=head_size)(inputs, inputs)
    attn = Dropout(dropout)(attn)
    x = Add()([inputs, attn]); x = LayerNormalization(epsilon=1e-6)(x)
    ff = Dense(ff_dim, activation='relu')(x); ff = Dense(inputs.shape[-1])(ff)
    ff = Dropout(dropout)(ff)
    x = Add()([x, ff]); x = LayerNormalization(epsilon=1e-6)(x)
    return x

def build_transformer():
    inputs = Input(shape=input_shape)
    x = Dense(16)(inputs)
    x = transformer_block(x)
    x = GlobalAveragePooling1D()(x)
    x = Dense(16, activation='relu')(x); x = Dropout(0.3)(x)
    outputs = Dense(1)(x)
    m = Model(inputs, outputs, name='Transformer')
    m.compile(optimizer=Adam(1e-4, clipnorm=1.0), loss='mse', metrics=['mae'])
    return m

def build_cnn_lstm():
    inputs = Input(shape=input_shape)
    x = Conv1D(16, 3, activation='relu', padding='same')(inputs)
    x = MaxPooling1D(2)(x)
    x = LSTM(16)(x); x = Dropout(0.3)(x)
    x = Dense(8, activation='relu')(x)
    outputs = Dense(1)(x)
    m = Model(inputs, outputs, name='CNN_LSTM')
    m.compile(optimizer=Adam(1e-3), loss='mse', metrics=['mae'])
    return m

models_dict = {
    'LSTM':        build_lstm(),
    'GRU':         build_gru(),
    'Transformer': build_transformer(),
    'CNN_LSTM':    build_cnn_lstm()
}

# ============================================================
# 5. TRAIN
# ============================================================
early_stop = EarlyStopping(monitor='val_loss', patience=15, restore_best_weights=True)
reduce_lr = ReduceLROnPlateau(monitor='val_loss', factor=0.5, patience=5)

results = {}
for name, model in models_dict.items():
    print(f"\nTraining {name}...")
    t0 = time.time()
    model.fit(X_train, y_train, validation_data=(X_val, y_val),
              epochs=100, batch_size=32,
              callbacks=[early_stop, reduce_lr], verbose=0)
    t_train = time.time() - t0

    y_pred = model.predict(X_test, verbose=0)
    y_test_orig = scaler_y.inverse_transform(y_test)
    y_pred_orig = scaler_y.inverse_transform(y_pred)

    rmse = np.sqrt(mean_squared_error(y_test_orig, y_pred_orig))
    mae = mean_absolute_error(y_test_orig, y_pred_orig)
    r2 = r2_score(y_test_orig, y_pred_orig)

    results[name] = {
        'RMSE': rmse, 'MAE': mae, 'R2': r2,
        'Params': model.count_params(),
        'Train_s': t_train,
        'y_pred': y_pred_orig.flatten()
    }
    print(f"  R²={r2:.4f}, RMSE={rmse:.5f}, MAE={mae:.5f}")

# ============================================================
# 6. RESULTS
# ============================================================
results_df = pd.DataFrame(results).T
results_df = results_df[['RMSE', 'MAE', 'R2', 'Params', 'Train_s']]
